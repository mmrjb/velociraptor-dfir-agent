import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { expect, type Page } from "@playwright/test";

export const REPO = path.resolve(process.cwd(), "..");

/** Start an existing-flow investigation through the UI's own API session. */
export async function startFlow(page: Page, client: string, flow: string, noLlm = true): Promise<string> {
  if (page.url() === "about:blank") await page.goto("/");
  const id = await page.evaluate(async ([client, flow, noLlm]) => {
    const s = await (await fetch("/api/v1/session")).json();
    const h = { "Content-Type": "application/json", "X-CSRF-Token": s.data.csrf_token };
    const plan = await (await fetch("/api/v1/plans", { method: "POST", headers: h, body: JSON.stringify({ mode: "existing_flow", org_id: "OSYNTHLAB", client_id: client, flow_id: flow, no_llm: noLlm }) })).json();
    const inv = await (await fetch("/api/v1/investigations", { method: "POST", headers: h, body: JSON.stringify({ plan_token: plan.data.plan_token }) })).json();
    return inv.data.investigation_id as string;
  }, [client, flow, noLlm] as const);
  await expect.poll(async () => page.evaluate(async (id) => {
    const d = (await (await fetch(`/api/v1/investigations/${id}`)).json()).data;
    return !d.job_active && !["queued", "running"].includes(d.investigation.job.state);
  }, id), { timeout: 30_000 }).toBe(true);
  return id;
}

/** Synthetic demo bundles generated by the test-only generator (never shipped). */
export function demoBundles(): string {
  const out = path.join(REPO, "frontend", "test-results", "demo-bundles");
  if (!existsSync(path.join(out, "fleet-baseline.tar.gz"))) {
    mkdirSync(out, { recursive: true });
    const python = process.env.VR_DFIR_PYTHON ?? (existsSync(path.join(REPO, ".venv/bin/python")) ? path.join(REPO, ".venv/bin/python") : "python3");
    execFileSync(python, [path.join(REPO, "tests/support/demo_bundles.py"), out], {
      env: { ...process.env, PYTHONPATH: [path.join(REPO, "src"), path.join(REPO, "tests"), process.env.PYTHONPATH].filter(Boolean).join(":") },
    });
  }
  return out;
}

/** Records model requests; ordinary navigation must not make any. */
export function watchModelRequests(page: Page): string[] {
  const seen: string[] = [];
  page.on("request", (r) => {
    if (/\/explain(\?|$)/.test(new URL(r.url()).pathname)) seen.push(r.url());
  });
  return seen;
}
